// Generator: parses firebird_dba_tasks_table_v3.md (the single source of
// truth) and emits internal/policy/ops_v3_gen.go. Drift protection: CI runs
// `go generate ./internal/policy` then `git diff --exit-code` — the plan and
// the code cannot silently diverge (main plan §8).
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type op struct {
	Num      int
	Category string
	Action   string
	Risk     string // Critical|High|Medium|Low
	OpType   string // Read|Write
	ExclDB   bool
	ExclObj  bool
	Restart  bool
}

func main() {
	// FBMCP_MD: path to firebird_dba_tasks_table_v3.md (default: repo root layout)
	src := os.Getenv("FBMCP_MD")
	if src == "" {
		src = `E:/Projects_2026/AIDBA/firebird_dba_tasks_table_v3.md`
	}

	b, err := os.ReadFile(src)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: read v3 table: %v\n", err)
		os.Exit(1)
	}
	var ops []op
	inTable := false
	for _, line := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(line, "| # | Category") {
			inTable = true
			continue
		}
		if inTable {
			if !strings.HasPrefix(line, "|") {
				if len(ops) > 0 {
					break // table ended
				}
				continue
			}
			if strings.HasPrefix(line, "|---") {
				continue
			}
			if o, ok := parseRow(line); ok {
				ops = append(ops, o)
			}
		}
	}
	if len(ops) < 100 {
		fmt.Fprintf(os.Stderr, "gen: parsed only %d ops — refusing to emit\n", len(ops))
		os.Exit(1)
	}

	var b2 strings.Builder
	fmt.Fprintf(&b2, "// Code generated by internal/gen/fromv3 from firebird_dba_tasks_table_v3.md. DO NOT EDIT.\n\npackage policy\n\n// V3Ops mirrors the operations table (111 rows). Tool tier mapping: see TierForRisk.\nvar V3Ops = []V3Op{\n")
	for _, o := range ops {
		fmt.Fprintf(&b2, "\t{Num: %d, Category: %q, Action: %q, Risk: %q, OpType: %q, ExclDB: %v, ExclObj: %v, Restart: %v},\n",
			o.Num, o.Category, o.Action, o.Risk, o.OpType, o.ExclDB, o.ExclObj, o.Restart)
	}
	b2.WriteString("}\n")
	out := filepath.Join("internal", "policy", "ops_v3_gen.go")
	if err := os.WriteFile(out, []byte(b2.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen: write:", err)
		os.Exit(1)
	}
	fmt.Printf("gen: wrote %d ops to %s\n", len(ops), out)
}

func parseRow(line string) (op, bool) {
	cells := strings.Split(strings.Trim(line, "|"), "|")
	if len(cells) < 11 {
		return op{}, false
	}
	var o op
	if _, err := fmt.Sscanf(strings.TrimSpace(cells[0]), "%d", &o.Num); err != nil {
		return op{}, false
	}
	o.Category = clean(cells[1])
	o.Action = clean(cells[2])
	o.Restart = yes(cells[3])
	o.ExclDB = yes(cells[4])
	o.ExclObj = yes(cells[5])
	o.Risk = clean(cells[8])
	o.OpType = clean(cells[9])
	return o, o.Risk != "" && o.OpType != ""
}

func clean(s string) string {
	s = strings.TrimSpace(s)
	s = strings.ReplaceAll(s, `"`, `'`)
	return s
}

func yes(s string) bool {
	return strings.Contains(strings.ToLower(s), "yes") || strings.Contains(s, "Да")
}
